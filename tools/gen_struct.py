#!/usr/bin/env python3
"""Writes a C struct from a table of its fields, putting padding wherever the table says nothing.

For a large struct that is known in patches, such as the speech engine's state. Each line of the table is

    OFFSET SIZE DECLARATION; // COMMENT

such as "0x0EE1C 0xC0 OSThread thread; // Synthesizes". Lines may be in any order, so tables can be joined. Two
fields that overlap are an error, unless they are the same line twice.
"""
import argparse
import re
import sys
from pathlib import Path

LINE = re.compile(r"^(0x[0-9A-Fa-f]+)\s+(0x[0-9A-Fa-f]+)\s+([^;]+;)\s*(//.*)?$")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("table", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--name", required=True, help="name of the struct")
    parser.add_argument("--size", required=True, type=lambda v: int(v, 0), help="size of the struct")
    args = parser.parse_args()

    fields = {}
    for number, line in enumerate(args.table.read_text(encoding="utf-8").splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        match = LINE.match(line)
        if not match:
            print(f"{args.table}:{number}: not a field: {line}", file=sys.stderr)
            return 1
        offset, size = int(match[1], 16), int(match[2], 16)
        entry = (size, match[3], match[4] or "")
        if offset in fields and fields[offset][:2] != entry[:2]:
            print(f"{args.table}:{number}: {offset:#x} is declared twice: {fields[offset][1]} and {match[3]}",
                  file=sys.stderr)
            return 1
        fields[offset] = entry

    width = len(f"{args.size:X}")
    lines = [f"// Generated by tools/gen_struct.py from {args.table.name}, do not edit", "",
             f"typedef struct {args.name} {{"]
    position = 0
    for offset in sorted(fields):
        size, declaration, comment = fields[offset]
        if offset < position:
            print(f"{args.table}: {declaration} at {offset:#x} overlaps the field before it", file=sys.stderr)
            return 1
        if offset > position:
            lines.append(f"    /* 0x{position:0{width}X} */ u8 pad_{position:0{width}X}[0x{offset - position:X}];")
        lines.append(f"    /* 0x{offset:0{width}X} */ {declaration}{' ' + comment if comment else ''}")
        position = offset + size
    if position > args.size:
        print(f"{args.table}: the fields go past the struct's size", file=sys.stderr)
        return 1
    if position < args.size:
        lines.append(f"    /* 0x{position:0{width}X} */ u8 pad_{position:0{width}X}[0x{args.size - position:X}];")
    lines += [f"}} {args.name}; // 0x{args.size:X}", ""]
    args.output.write_text("\n".join(lines), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
