// The faces on the pictures of the right-job scenes. Overlay 71 (RightJob2Scene, which mounts its pictures as
// "Job/job000_LZ.bin" and on) has the same arrays and reads them through the same table, of 120 pictures with one
// to four faces each. This overlay reads none of it, yet its .rodata holds all 120 arrays, and not the table: the
// file had them and a function that read the table, which the link dropped with the table (see
// Marriage2Scene_UnusedGetJobFaces). Its scene is laid out as overlay 71's is, and loads the same files from its
// pictures ("3BG:/bg.nsc", "3BG:/body.imd"), so it is likely to have been made from that scene's source (inferred).
// The arrays are named after their pictures' indices in sJobPictures.

// One face on a picture, in the units of FaceCast::SetTransform(int, u16, int, s8, u8, u8, u8, u8)
struct JobFace {
    /* 0x0 */ u16 mId;
    /* 0x2 */ s8 mX;
    /* 0x3 */ s8 mY;
    /* 0x4 */ u8 mScale;
    /* 0x5 */ u8 mRotX;
    /* 0x6 */ u8 mRotY;
    /* 0x7 */ u8 mRotZ;
}; // 0x8

// One picture
struct JobPicture {
    /* 0x0 */ const JobFace *mFaces;
    /* 0x4 */ u8 mFaceCount;
    /* 0x5 */ u8 mUnknown5;
    /* 0x6 */ u8 mUnknown6;
    /* 0x7 */ u8 mUnknown7;
    /* 0x8 */ int mUnknown8;
    /* 0xC */ int mUnknownC;
}; // 0x10

// A position in pixels
struct TextPosition {
    int x;
    int y;
};

// When each picture is taken down: the picture, and the frame of the scene by which the next one is to be up
struct PictureTime {
    /* 0x0 */ int mPicture;
    /* 0x4 */ u16 mEndFrame;
}; // 0x8

